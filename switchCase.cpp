#include <bits/stdc++.h>
using namespace std;

int main() {

    int day;

    cout << "Enter a number (1-3): ";
    cin >> day;

    switch (day){
        case 1:
            cout << "You are case 1";
            break;
        case 2:
            cout << "You are case 2"; 
            break;
        case 3:
            cout << "You are case 3";
            break;
        default:
            cout << "You are default";
    }
}

